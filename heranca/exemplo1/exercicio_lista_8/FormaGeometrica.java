public class FormaGeometrica {
    protected double area;
    protected double perimetro;

    public double calcularArea() {
        return area;
    }

    public double calcularPerimetro() {
        return perimetro;
    }

    public double getArea() {
        return area;
    }

    public double getPerimetro() {
        return perimetro;
    }
}
